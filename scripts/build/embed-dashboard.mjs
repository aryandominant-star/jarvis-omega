// Embeds the built dashboard (apps/web-dashboard/dist) into the Worker as src/static.ts so a single
// `wrangler deploy` serves the SPA and the API from the same origin (no CORS, no third-party cookies).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const dist = path.join(root, "apps/web-dashboard/dist");
const outFile = path.join(root, "apps/cloud-control-plane/src/static.ts");
const types = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".ico": "image/x-icon", ".json": "application/json", ".woff2": "font/woff2" };
const assets = {};
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full);
    else if (!e.name.startsWith(".")) {
      const rel = "/" + path.relative(dist, full).split(path.sep).join("/");
      assets[rel] = { ct: types[path.extname(e.name).toLowerCase()] ?? "application/octet-stream", b64: fs.readFileSync(full).toString("base64") };
    }
  }
};
if (process.argv.includes("--empty") || !fs.existsSync(dist)) {
  fs.writeFileSync(outFile, "// AUTO-GENERATED by build. Empty: API-only deployment.\nexport const ASSETS: Record<string,{ct:string;b64:string}> = {};\n");
  console.log("static.ts: empty (API only)");
} else {
  walk(dist);
  fs.writeFileSync(outFile, "// AUTO-GENERATED by build. The dashboard SPA, embedded so the Worker serves it at the same origin.\nexport const ASSETS: Record<string,{ct:string;b64:string}> = " + JSON.stringify(assets) + ";\n");
  console.log(`static.ts: ${Object.keys(assets).length} files, ${(fs.statSync(outFile).size / 1024).toFixed(0)} KB`);
}
